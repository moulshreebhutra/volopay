import type { Config, Finding, Policy } from "./model";
import { MODULES, isUnresolved, unresolvedLabel, money } from "./model";
import { deriveDepartments, deriveLocations, personByEmail } from "./people";
import { SOURCES } from "./rules";

const q = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
const row = (cells: string[]) => cells.map(q).join(",");

export function peopleInviteCsv(cfg: Config): string {
  const lines = [row(["email", "role", "department", "location", "name", "title"])];
  for (const p of cfg.people) if (p.email) lines.push(row([p.email, p.role, p.department, p.location, p.name, p.title]));
  return lines.join("\n") + "\n";
}

export function departmentsCsv(cfg: Config): string {
  const lines = [row(["department", "managers", "how_manager_was_found"])];
  for (const d of deriveDepartments(cfg.people)) {
    lines.push(row([d.name, d.managers.map((m) => personByEmail(cfg.people, m)?.name || m).join("; "), d.managerSource === "marked" ? "marked in sheet" : d.managerSource === "title" ? "inferred from title" : "none found"]));
  }
  return lines.join("\n") + "\n";
}

function approverName(cfg: Config, a: string): string {
  if (isUnresolved(a)) return `UNRESOLVED: ${unresolvedLabel(a)}`;
  const p = personByEmail(cfg.people, a);
  return p ? `${p.name || p.email} <${p.email}>` : a;
}

function scopeText(p: Policy): string {
  return p.scope.type === "company" ? "Company (default)" : `Department: ${p.scope.department}`;
}

export function policiesCsv(cfg: Config): string {
  const lines = [row(["module", "applies_to", "amount_from", "amount_to", "level_1", "level_2", "level_3", "level_4", "level_5"])];
  for (const p of cfg.policies) {
    for (const r of p.ranges) {
      const lv = [0, 1, 2, 3, 4].map((i) => (r.levels[i] ? approverName(cfg, r.levels[i]) : i === 0 && r.levels.length === 0 ? "auto-approved" : ""));
      lines.push(row([MODULES.find((m) => m.id === p.module)?.label ?? p.module, scopeText(p), String(r.from), r.to === null ? "no limit" : String(r.to), ...lv]));
    }
  }
  return lines.join("\n") + "\n";
}

export function policiesJson(cfg: Config): string {
  return JSON.stringify(
    {
      note: "Draft generated by the setup studio. Volopay has no public import for this; it is the input an admin or Customer Success Manager keys in.",
      currency: cfg.currency,
      makerChecker: cfg.makerChecker,
      submissionPolicy: cfg.submission,
      policies: cfg.policies,
    },
    null,
    2,
  );
}

/** The checklist follows the order of Volopay's own Admin Guide. */
export function checklistMd(cfg: Config, findings: Finding[]): string {
  const depts = deriveDepartments(cfg.people);
  const locs = deriveLocations(cfg.people);
  const errors = findings.filter((f) => f.severity === "error");
  const warnings = findings.filter((f) => f.severity === "warning");
  const L: string[] = [];
  L.push(`# Volopay setup pack: ${cfg.company}`);
  L.push("");
  L.push(`Follows the order of the [${SOURCES.admin.label}](${SOURCES.admin.url}). Draft, to be checked by an Admin or Customer Success Manager.`);
  L.push("");
  L.push(`## Before you start`);
  L.push(errors.length ? `${errors.length} blocking ${errors.length === 1 ? "issue" : "issues"} to fix first:` : "No blocking issues found.");
  for (const e of errors) L.push(`- [ ] **${e.title}.** ${e.detail} *Fix:* ${e.fix}`);
  if (warnings.length) {
    L.push("");
    L.push(`${warnings.length} ${warnings.length === 1 ? "warning" : "warnings"} to review:`);
    for (const w of warnings) L.push(`- [ ] **${w.title}.** ${w.detail}`);
  }
  L.push("");
  L.push(`## 1. Invite users and assign roles (Manage > People)`);
  L.push(`- [ ] Invite ${cfg.people.filter((p) => p.email).length} people. File: \`people-invites.csv\`.`);
  L.push(`- [ ] Roles: ${count(cfg.people.map((p) => p.role))}.`);
  L.push(`## 2. Create departments (Manage > Company)`);
  for (const d of depts) L.push(`- [ ] ${d.name}: manager ${d.managers.length ? d.managers.map((m) => personByEmail(cfg.people, m)?.name || m).join(", ") : "**none found**"}.`);
  L.push(`## 3. Add locations (Manage > Locations)`);
  for (const l of locs) L.push(`- [ ] ${l}`);
  L.push(`## 4. Set up policies (Manage > Settings)`);
  L.push(`- [ ] Maker-checker: ${MODULES.map((m) => `${m.label.split(" (")[0]} ${cfg.makerChecker[m.id] ? "on" : "off"}`).join("; ")}.`);
  L.push(`- [ ] Submission policy: receipt required ${cfg.submission.receiptAbove === null ? "never" : cfg.submission.receiptAbove === 0 ? "on every transaction" : `above ${money(cfg.submission.receiptAbove, cfg.currency)}`}; memo ${cfg.submission.memoRequired ? "required" : "optional"}.`);
  for (const p of cfg.policies) {
    L.push(`- [ ] **${MODULES.find((m) => m.id === p.module)?.label}, ${scopeText(p)}**`);
    for (const r of p.ranges) {
      const who = r.levels.length ? r.levels.map((a, i) => `L${i + 1} ${approverName(cfg, a)}`).join(" → ") : "auto-approved";
      L.push(`  - ${money(r.from, cfg.currency)} to ${r.to === null ? "no limit" : money(r.to, cfg.currency)}: ${who}`);
    }
  }
  L.push(`## 5. Configure modules`);
  L.push(`- [ ] Cards, bill pay and reimbursement settings are not generated by this tool; follow the Admin Guide.`);
  L.push(`## 6. Accounting`);
  L.push(`- [ ] Integrate ${cfg.accounting}.${cfg.accounting === "Other / not decided" ? " Start with Universal CSV." : ""}`);
  L.push("");
  L.push(`---`);
  L.push(`Sources: [${SOURCES.admin.label}](${SOURCES.admin.url}), [${SOURCES.approval.label}](${SOURCES.approval.url}), [${SOURCES.roles.label}](${SOURCES.roles.url}).`);
  return L.join("\n") + "\n";
}

function count(items: string[]): string {
  const m = new Map<string, number>();
  for (const i of items) m.set(i, (m.get(i) ?? 0) + 1);
  return [...m.entries()].map(([k, v]) => `${v} ${k}`).join(", ");
}
